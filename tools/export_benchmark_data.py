"""Embed an I8ML model, one raw MNIST image, and exact golden results. Stdlib only."""
import argparse
import hashlib
from pathlib import Path
import struct

HEADER = struct.Struct('<4s8I')
INPUT, HIDDEN, OUTPUT = 784, 128, 10
MODEL_SIZE = HEADER.size + INPUT * HIDDEN + HIDDEN * OUTPUT + 4 * (HIDDEN + OUTPUT)


def read_model(path):
    data = Path(path).read_bytes()
    if len(data) != MODEL_SIZE:
        raise ValueError(f'model must contain {MODEL_SIZE} bytes')
    magic, version, ni, nh, no, xf, wf1, hf, wf2 = HEADER.unpack_from(data)
    if (magic, version, ni, nh, no, xf) != (b'I8ML', 1, INPUT, HIDDEN, OUTPUT, 6):
        raise ValueError('invalid I8ML header')
    if not (4 <= wf1 <= 10 and 4 <= wf2 <= 10 and 4 <= hf <= 7):
        raise ValueError('unsupported fractional bits')
    offset = HEADER.size
    q = {'w1_frac': wf1, 'hidden_frac': hf, 'w2_frac': wf2}
    for name, count, fmt in [('w1', INPUT * HIDDEN, 'b'), ('w2', HIDDEN * OUTPUT, 'b'),
                              ('b1', HIDDEN, 'i'), ('b2', OUTPUT, 'i')]:
        q[name] = struct.unpack_from('<' + str(count) + fmt, data, offset)
        offset += count * struct.calcsize('<' + fmt)
    if any(abs(v) > 1 << 24 for name in ('b1', 'b2') for v in q[name]):
        raise ValueError('bias exceeds safe accumulator bound')
    return q, hashlib.sha256(data).hexdigest()


def forward(q, x):
    # Python integers provide a separate unbounded-width reference for INT32 code.
    shift = 6 + q['w1_frac'] - q['hidden_frac']
    h = []
    for r in range(HIDDEN):
        acc = q['b1'][r] + sum(a * b for a, b in zip(x, q['w1'][r * INPUT:(r + 1) * INPUT]))
        h.append(min(127, (max(0, acc) + (1 << (shift - 1))) >> shift))
    scores = [q['b2'][r] + sum(a * b for a, b in zip(h, q['w2'][r * HIDDEN:(r + 1) * HIDDEN]))
              for r in range(OUTPUT)]
    return h, scores, max(range(OUTPUT), key=lambda i: scores[i])


def initializer(values):
    # Keep lines short enough for diagnostics and manual inspection of generated data.
    chunks = [','.join(str(v) for v in values[i:i + 32]) for i in range(0, len(values), 32)]
    return '{\n' + ',\n'.join(chunks) + '\n}'


def export(model, image, output):
    q, model_hash = read_model(model)
    raw = Path(image).read_bytes()
    if len(raw) != INPUT:
        raise ValueError('image must contain exactly 784 raw grayscale bytes')
    inputs = [[(v * 64 + 127) // 255 for v in raw], [-128] * INPUT, [127] * INPUT, [0] * INPUT]
    golden = [forward(q, x) for x in inputs]
    lines = ['/* Generated by tools/export_benchmark_data.py. Do not edit. */',
             '#ifndef BENCHMARK_DATA_H', '#define BENCHMARK_DATA_H', '#include "mlp.h"',
             f'#define BENCHMARK_CASES {len(inputs)}u',
             f'#define BENCHMARK_MODEL_SHA256 "{model_hash}"',
             f'#define BENCHMARK_IMAGE_SHA256 "{hashlib.sha256(raw).hexdigest()}"',
             'static const mlp_model benchmark_model = {']
    for name in ('w1', 'w2', 'b1', 'b2'):
        lines.append(f'.{name} = {initializer(q[name])},')
    for name in ('w1_frac', 'hidden_frac', 'w2_frac'):
        lines.append(f'.{name} = {q[name]},')
    lines.append('};')
    for name, ctype, width, rows in [('inputs', 'int8_t', INPUT, inputs),
                                     ('hidden', 'int8_t', HIDDEN, [g[0] for g in golden]),
                                     ('scores', 'int32_t', OUTPUT, [g[1] for g in golden])]:
        lines.append(f'static const {ctype} benchmark_{name}[BENCHMARK_CASES][{width}] = {{')
        lines += [initializer(row) + ',' for row in rows]
        lines.append('};')
    lines += ['static const int benchmark_predictions[BENCHMARK_CASES] = ' +
              initializer([g[2] for g in golden]) + ';', '#endif']
    Path(output).write_text('\n'.join(lines) + '\n')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--model', required=True)
    p.add_argument('--image', required=True)
    p.add_argument('--out', required=True)
    a = p.parse_args()
    export(a.model, a.image, a.out)
    print('Exported benchmark model and four golden cases:', a.out)


if __name__ == '__main__':
    main()
